#!/usr/bin/env node
/**
 * Composer: assemble src/tools.ts from per-tool registration templates,
 * driven by a tools-config.json.
 *
 * Usage:
 *   node compose.mjs --config <tools-config.json> --templates <dir> --out <dest>
 *
 * Each template at <templates>/<tool>.ts.tmpl is the body of a single
 * server.tool(...) registration. The composer concatenates the chosen tools
 * in order, splits read vs write tools at the // ---------- write tools ----------
 * marker, and substitutes placeholders.
 *
 * Placeholders supported:
 *   {{FILTERABLE_FIELDS_TS}}   -> '["type", "client", "status"]'
 *   {{FILTERABLE_FIELDS_ZOD}}  -> zod schema fragments for each filter (multi-line)
 *   {{WIKILINKS_STYLE}}        -> "obsidian" | "markdown" | "none"
 *   {{SUBPATH}}                -> "wiki" or ""
 *   {{PROJECT_NAME}}           -> "Acme Engineering Wiki"
 */
import { promises as fs } from "node:fs";
import path from "node:path";

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const key = a.slice(2);
      const val = argv[i + 1];
      out[key] = val;
      i++;
    }
  }
  return out;
}

const args = parseArgs(process.argv.slice(2));
for (const required of ["config", "templates", "out"]) {
  if (!args[required]) {
    console.error(`Missing --${required}`);
    process.exit(2);
  }
}

const cfg = JSON.parse(await fs.readFile(args.config, "utf8"));

const READ_TOOLS_DEFAULT = [
  "wiki_search",
  "wiki_read_page",
  "wiki_list_pages",
  "wiki_get_related",
  "wiki_get_index",
  "wiki_get_log",
  "wiki_sync",
];
const WRITE_TOOLS = ["wiki_create_page", "wiki_update_page", "wiki_append_to_log"];

const chosen = cfg.tools && cfg.tools.length ? cfg.tools : [
  ...READ_TOOLS_DEFAULT,
  ...(cfg.enable_writes ? WRITE_TOOLS : []),
];

// Strip get_related if wikilinks_style is "none"
const filtered = chosen.filter((t) => {
  if (t === "wiki_get_related" && cfg.wikilinks_style === "none") return false;
  return true;
});

const readTools = filtered.filter((t) => !WRITE_TOOLS.includes(t));
const writeTools = filtered.filter((t) => WRITE_TOOLS.includes(t));

function tsArray(values) {
  if (!values || values.length === 0) return "[]";
  return "[" + values.map((v) => JSON.stringify(v)).join(", ") + "]";
}

function zodFilterFragments(fields) {
  if (!fields || fields.length === 0) return "";
  return fields
    .map(
      (f) =>
        `      ${JSON.stringify(f)}: z.string().optional().describe("Filter by frontmatter.${f}"),`
    )
    .join("\n");
}

const substitutions = {
  FILTERABLE_FIELDS_TS: tsArray(cfg.filterable_fields),
  FILTERABLE_FIELDS_ZOD: zodFilterFragments(cfg.filterable_fields),
  WIKILINKS_STYLE: cfg.wikilinks_style || "obsidian",
  SUBPATH: cfg.subpath || "",
  PROJECT_NAME: cfg.project_name || cfg.slug,
  SLUG: cfg.slug,
};

function applySubs(src) {
  return src.replace(/\{\{([A-Z0-9_]+)\}\}/g, (_, key) => {
    if (key in substitutions) return substitutions[key];
    return `{{${key}}}`; // leave unknown placeholders for later passes
  });
}

async function loadTool(name) {
  const file = path.join(args.templates, `${name}.ts.tmpl`);
  try {
    const raw = await fs.readFile(file, "utf8");
    return applySubs(raw).trimEnd();
  } catch (e) {
    console.error(`Missing template: ${file}`);
    throw e;
  }
}

const header = `// AUTO-GENERATED by wiki-to-mcp skill. Re-run the skill to regenerate this file.
// Hand-edit between tool registrations only if you know what you're doing.

import { z } from "zod";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import type { WikiSource } from "./wiki.js";
import {
  extractMarkdownLinks,
  extractWikiLinks,
  renderFrontmatter,
  searchPages,
} from "./search.js";

function textResult(text: string) {
  return { content: [{ type: "text" as const, text }] };
}

function jsonResult(value: unknown) {
  return textResult(JSON.stringify(value, null, 2));
}

export function registerWikiTools(server: McpServer, repo: WikiSource): void {
  const wikiRoot = repo.wikiRoot();

  // ---------- read tools ----------
`;

const middleMarker = `
  // ---------- write tools ----------
`;

const footer = `
}
`;

const readBlocks = [];
for (const t of readTools) {
  readBlocks.push(await loadTool(t));
}

const writeBlocks = [];
for (const t of writeTools) {
  writeBlocks.push(await loadTool(t));
}

const composed =
  header +
  readBlocks.join("\n\n") +
  middleMarker +
  (writeBlocks.length ? writeBlocks.join("\n\n") : "  // (no write tools configured)") +
  footer;

await fs.mkdir(path.dirname(args.out), { recursive: true });
await fs.writeFile(args.out, composed, "utf8");

console.error(
  `composed ${readTools.length} read tool(s) + ${writeTools.length} write tool(s) -> ${args.out}`
);
